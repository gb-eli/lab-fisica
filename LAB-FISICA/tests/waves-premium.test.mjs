import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const project=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const required=['js/science/waves-optics.js','js/modules/waves.js','js/modules/waves3d.js','css/waves-lab.css','docs/ONDAS_SOM_OPTICA_PREMIUM_360.md'];
await Promise.all(required.map(file=>access(resolve(project,file))));
const ui=await readFile(resolve(project,'js/modules/waves.js'),'utf8');
const scene=await readFile(resolve(project,'js/modules/waves3d.js'),'utf8');
const css=await readFile(resolve(project,'css/waves-lab.css'),'utf8');
const app=await readFile(resolve(project,'js/app.js'),'utf8');
const index=await readFile(resolve(project,'index.html'),'utf8');
const hall=await readFile(resolve(project,'js/modules/hall.js'),'utf8');
const catalog=await readFile(resolve(project,'js/labs/lab-catalog.js'),'utf8');
for(const mode of ['waves','resonance','acoustics','doppler','optics','photonics'])assert.match(ui,new RegExp(`${mode}:`));
assert.match(ui,/Ondas, Som e Óptica 360/);assert.match(ui,/Ouvir sinal seguro/);assert.match(ui,/Exportar evidência/);assert.match(ui,/waves-graph/);
for(const builder of ['createWaveTank','createResonance','createAcoustics','createDoppler','createOptics','createPhotonics'])assert.match(scene,new RegExp(builder));
assert.match(scene,/createRenderRuntime/);assert.match(scene,/createOrbitController/);assert.match(scene,/twoSourceInterference/);assert.match(scene,/snellRefraction/);assert.match(scene,/fiberGuidance/);assert.match(scene,/doubleSlit/);
assert.match(css,/waves-stage/);assert.match(css,/@media\(max-width:720px\)/);assert.match(app,/renderWaves/);assert.match(app,/waves:\s*\(/);assert.match(index,/css\/waves-lab\.css/);assert.match(catalog,/route: 'waves'/);assert.match(hall,/Versão 0\.4\.5/);
console.log('✓ Ondas, Som e Óptica Premium 360: seis experiências, áudio seguro, gráficos, mobile e Hall validados.');
