import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const project=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const required=['js/science/thermodynamics-fluids.js','js/modules/thermal.js','js/modules/thermal3d.js','css/thermal-lab.css','docs/TERMOLOGIA_GASES_FLUIDOS_PREMIUM_360.md'];
await Promise.all(required.map(file=>access(resolve(project,file))));
const ui=await readFile(resolve(project,'js/modules/thermal.js'),'utf8');
const scene=await readFile(resolve(project,'js/modules/thermal3d.js'),'utf8');
const css=await readFile(resolve(project,'css/thermal-lab.css'),'utf8');
const app=await readFile(resolve(project,'js/app.js'),'utf8');
const index=await readFile(resolve(project,'index.html'),'utf8');
const hall=await readFile(resolve(project,'js/modules/hall.js'),'utf8');
const catalog=await readFile(resolve(project,'js/labs/lab-catalog.js'),'utf8');
for(const mode of ['calorimetry','transfer','phasegas','hydrostatics','flow','machines'])assert.match(ui,new RegExp(`${mode}:`));
assert.match(ui,/Termologia, Gases e Fluidos 360/);assert.match(ui,/Exportar evidência/);assert.match(ui,/thermal-graph/);
for(const builder of ['createCalorimetry','createTransfer','createPhaseGas','createHydrostatics','createFlow','createMachines'])assert.match(scene,new RegExp(`function ${builder}`));
assert.match(scene,/createRenderRuntime/);assert.match(scene,/createOrbitController/);assert.match(scene,/calorimetryEquilibrium/);assert.match(scene,/bernoulli/);assert.match(scene,/heatEngine/);
assert.match(css,/thermal-stage/);assert.match(css,/@media\(max-width:720px\)/);assert.match(app,/renderThermal/);assert.match(app,/thermal:\s*\(/);assert.match(index,/css\/thermal-lab\.css/);assert.match(catalog,/route: 'thermal'/);assert.match(hall,/Versão 0\.4\.5/);
console.log('✓ Termologia, Gases e Fluidos Premium 360: seis experiências, 3D, gráficos, mobile, Hall e evidência validados.');
