import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const project=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const required=['js/science/mechanics.js','js/modules/mechanics.js','js/modules/mechanics3d.js','css/mechanics-lab.css','docs/MECANICA_GRAVIDADE_DINAMICA_PREMIUM_360.md'];
await Promise.all(required.map(file=>access(resolve(project,file))));
const ui=await readFile(resolve(project,'js/modules/mechanics.js'),'utf8');
const scene=await readFile(resolve(project,'js/modules/mechanics3d.js'),'utf8');
const css=await readFile(resolve(project,'css/mechanics-lab.css'),'utf8');
const app=await readFile(resolve(project,'js/app.js'),'utf8');
const index=await readFile(resolve(project,'index.html'),'utf8');
const hall=await readFile(resolve(project,'js/modules/hall.js'),'utf8');
const catalog=await readFile(resolve(project,'js/labs/lab-catalog.js'),'utf8');
for(const mode of ['dynamics','projectile','collision','oscillators','gravity'])assert.match(ui,new RegExp(`${mode}:`));
assert.match(ui,/Mecânica, Gravidade e Dinâmica 360/);assert.match(ui,/data-mechanics-timescale/);assert.match(ui,/Exportar evidência/);assert.match(ui,/mechanics-graph/);
for(const builder of ['createDynamicsMode','createProjectileMode','createCollisionMode','createOscillatorMode','createGravityMode'])assert.match(scene,new RegExp(builder));
assert.match(scene,/createRenderRuntime/);assert.match(scene,/createOrbitController/);assert.match(scene,/ArrowHelper/);assert.match(scene,/projectileFlight/);assert.match(scene,/collision1D/);
assert.match(css,/mechanics-stage/);assert.match(css,/@media\(max-width:720px\)/);assert.match(app,/renderMechanics/);assert.match(app,/mechanics:\s*\(/);assert.match(index,/css\/mechanics-lab\.css/);assert.match(catalog,/route: 'mechanics'/);assert.match(hall,/Versão 0\.4\.5/);
console.log('✓ Mecânica Premium 360: cinco experiências, vetores, câmera lenta, gráficos, mobile e Hall validados.');
