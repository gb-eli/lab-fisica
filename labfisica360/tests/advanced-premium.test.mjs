import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const project=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const required=['js/science/advanced-physics.js','js/modules/advanced.js','js/modules/advanced3d.js','css/advanced-lab.css','docs/FISICA_AVANCADA_PREMIUM_360.md'];
await Promise.all(required.map(file=>access(resolve(project,file))));
const ui=await readFile(resolve(project,'js/modules/advanced.js'),'utf8');
const scene=await readFile(resolve(project,'js/modules/advanced3d.js'),'utf8');
const css=await readFile(resolve(project,'css/advanced-lab.css'),'utf8');
const registry=await readFile(resolve(project,'js/labs/route-registry.js'),'utf8');
const hall=await readFile(resolve(project,'js/modules/hall.js'),'utf8');
const catalog=await readFile(resolve(project,'js/labs/lab-catalog.js'),'utf8');
for(const mode of ['quantum','darkMatter','relativity','blackHole','timeTravel'])assert.match(ui,new RegExp(`${mode}:`));
assert.match(ui,/Física Avançada 360/);assert.match(ui,/Exportar evidência/);assert.match(ui,/advanced-graph/);assert.match(ui,/calculateAdvancedExperiment/);
for(const builder of ['buildQuantum','buildRelativity','buildDarkMatter','buildBlackHole','buildCausality'])assert.match(scene,new RegExp(`function ${builder}`));
assert.match(scene,/createRenderRuntime/);assert.match(scene,/createOrbitController/);assert.match(scene,/getExperimentState/);
assert.match(css,/advanced-premium__layout/);assert.match(css,/@media\(max-width:760px\)/);assert.match(registry,/advanced-lab\.css/);assert.match(registry,/import\('\.\.\/modules\/advanced\.js'\)/);assert.match(catalog,/route: 'advanced'/);assert.match(hall,/Versão 0\.5\.0/);
console.log('✓ Física Avançada Premium 360: cinco observatórios, gráficos, parâmetros, mobile, Hall e evidência validados.');
