import assert from 'node:assert/strict';
import { DEFAULT_LOADS, householdEnergyState, solarGeneration, windGeneration, batteryDispatch, distributionState, circuitProtectionState } from '../js/science/energy-grid.js';
const enabled = Object.fromEntries(DEFAULT_LOADS.map((load) => [load.id, true]));
const base = householdEnergyState({ enabled, solar: { ratedKw: 0, irradiance: 0 }, wind: { ratedKw: 0, windSpeed: 0 }, battery: { capacityKwh: 10, soc: 0.5, requestedKw: 0 } });
assert.ok(base.loadKw > 9);
assert.ok(base.branches.shower.current > 40);
assert.equal(base.branches.shower.breakerTrip, true);
assert.equal(circuitProtectionState({ current: 8, breaker: 20, leakageMa: 5 }).state, 'normal');
assert.equal(circuitProtectionState({ current: 2, breaker: 20, leakageMa: 35 }).drTrip, true);
const solarLow = solarGeneration({ ratedKw: 5, irradiance: 300, cellTemperature: 25, shading: 0 });
const solarHigh = solarGeneration({ ratedKw: 5, irradiance: 900, cellTemperature: 25, shading: 0 });
assert.ok(solarHigh.acKw > solarLow.acKw);
assert.ok(solarGeneration({ ratedKw: 5, irradiance: 900, cellTemperature: 70, shading: 0 }).acKw < solarHigh.acKw);
assert.ok(windGeneration({ windSpeed: 8, ratedKw: 10 }).electricalKw > windGeneration({ windSpeed: 4, ratedKw: 10 }).electricalKw * 5);
assert.ok(batteryDispatch({ capacityKwh: 10, soc: 0.5, requestedKw: 3, hours: 1 }).nextSoc < 0.5);
assert.ok(batteryDispatch({ capacityKwh: 10, soc: 0.5, requestedKw: -3, hours: 1 }).nextSoc > 0.5);
const shortLine = distributionState({ loadKw: 6, lineLengthKm: 0.2 });
const longLine = distributionState({ loadKw: 6, lineLengthKm: 2 });
assert.ok(longLine.lineLossKw > shortLine.lineLossKw);
assert.ok(longLine.deliveredVoltage < shortLine.deliveredVoltage);
console.log('✓ Energia, casa elétrica e rede: testes científicos aprovados.');
