import assert from 'node:assert/strict';
import { access, readFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const project = resolve(dirname(fileURLToPath(import.meta.url)), '..');
for (const file of ['js/render/artistic-refinement.js','css/artistic-refinement.css','docs/REFINAMENTO_ARTISTICO_VALIDACAO_REAL.md']) await access(resolve(project,file));
const runtime = await readFile(resolve(project,'js/render/runtime.js'),'utf8');
const orbit = await readFile(resolve(project,'js/render/orbit-controller.js'),'utf8');
const materials = await readFile(resolve(project,'js/render/materials.js'),'utf8');
const index = await readFile(resolve(project,'index.html'),'utf8');
assert.match(runtime,/createArtisticRefinement/);
assert.match(runtime,/scene-camera-controls/);
assert.match(runtime,/bindCameraController/);
assert.match(orbit,/two|pinchMidpoint/);
assert.match(orbit,/lastTapAt/);
assert.match(orbit,/zoom\(factor/);
assert.match(orbit,/keydown/);
assert.match(materials,/clearcoat/);
assert.match(materials,/iridescence/);
assert.match(materials,/warning/);
assert.match(index,/id="surface-detail"/);
assert.match(index,/id="inspection-lighting"/);
assert.match(index,/id="camera-assist"/);
const assetManifest = JSON.parse(await readFile(resolve(project,'assets/models/electrical/manifest.json'),'utf8'));
assert.equal(assetManifest.version,'1.2.0');
assert.equal(assetManifest.artGrade,'premium-procedural-v2');
assert.ok(Object.values(assetManifest.assets).every((asset)=>asset.surfaceDetails === true));
console.log('✓ Refinamento artístico: materiais, luz de inspeção, câmera touch e assets premium v2 validados.');
