import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../js/session/student-session.js', import.meta.url), 'utf8');
const index = await readFile(new URL('../index.html', import.meta.url), 'utf8');
for (const field of ['student-name','student-class','student-shift']) assert.match(index, new RegExp(`id="${field}"`));
for (const action of ['student-login','switch-student','logout-student','export-session-json','export-session-csv']) assert.match(index, new RegExp(`id="${action}"`));
assert.match(source, /PROFILE_KEY/);
assert.match(source, /SESSION_KEY/);
assert.match(source, /HISTORY_KEY/);
assert.match(source, /activeSeconds/);
assert.match(source, /document\.hidden/);
assert.match(source, /visibilitychange/);
assert.match(source, /enterRoute/);
assert.match(source, /leaveRoute/);
assert.match(source, /finalize/);
assert.match(source, /exportJSON/);
assert.match(source, /exportCSV/);
assert.match(source, /manha/);
assert.match(source, /tarde/);
assert.match(source, /noite/);
assert.doesNotMatch(source, /fetch\(/, 'A sessão não pode enviar dados pela rede.');
console.log('✓ Sessão local: estudante, turma, turno, tempo, acessos, troca, logout e exportações validados.');
